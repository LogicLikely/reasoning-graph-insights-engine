    public const string Wide100 = "stress-wide-100";
    public const string SharedDiamond100 = "stress-shared-diamond-100";
    public const string Balanced1K = "stress-balanced-1k";
    public const string Wide1K = "stress-wide-1k";
    public const string Deep1K = "stress-deep-1k";
    public const string SharedDiamond1K = "stress-shared-diamond-1k";
    public const string Balanced10K = "stress-balanced-10k";
    public const string Wide10K = "stress-wide-10k";
    public const string Deep10K = "stress-deep-10k";
    public const string SharedDiamond10K = "stress-shared-diamond-10k";
    public const string Balanced100K = "stress-balanced-100k";
